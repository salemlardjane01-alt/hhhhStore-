/**
 * الحصول على قائمة بلديات الولاية المحددة
 */
export function getCommunesForWilaya(wilayaName: string): string[] {
  if (WILAYA_COMMUNES_MAP[wilayaName]) {
    return WILAYA_COMMUNES_MAP[wilayaName];
  }
  
  // بحث تقريبي في حال كان الاسم يحتوي على رقم الولاية
  const match = Object.keys(WILAYA_COMMUNES_MAP).find((k) =>
    wilayaName.startsWith(k.substring(0, 2))
  );

  if (match) {
    return WILAYA_COMMUNES_MAP[match];
  }

  return ['وسط المدينة / المقر الرئيسي', 'بلدية أخرى'];
}
